const dictionaries: Record<SupportedLanguage, Record<TranslationKey, string>> = {
  en,
  "zh-CN": zhCN,
  ja,
  ko,
  de,
  fr,
  es,
};

export function resolveLanguage(
  preference: LanguagePreference | string | undefined,
  systemLanguage = typeof navigator === "undefined" ? "en" : navigator.language,
): SupportedLanguage {
  if (isSupportedLanguage(preference)) {
    return preference;
  }

  const normalized = systemLanguage.toLowerCase();
  if (normalized.startsWith("zh")) {
    return "zh-CN";
  }

  const primary = normalized.split("-")[0];
  if (isSupportedLanguage(primary)) {
    return primary;
  }

  return "en";
}

export function normalizeLanguagePreference(value: string | undefined): LanguagePreference {
  if (value === "system" || isSupportedLanguage(value)) {
    return value;
  }

  return "system";
}

export function createTranslator(language: SupportedLanguage) {
  const dictionary = dictionaries[language] ?? dictionaries.en;

  return (key: TranslationKey, values?: Record<string, string | number>) => {
    const template = dictionary[key] ?? dictionaries.en[key] ?? key;
    if (!values) {
      return template;
    }

    return Object.entries(values).reduce(
      (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
      template,
    );
  };
}

function isSupportedLanguage(value: unknown): value is SupportedLanguage {
  return typeof value === "string" && supportedLanguages.includes(value as SupportedLanguage);
}
